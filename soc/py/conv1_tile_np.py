"""Two-position, two-filter conv1 test tile from Adv_Attack's model.pt, without needing PyTorch.

Mirrors the earlier PyTorch script conv1_tile.py (same test image, same quantization) and writes
a C header for the PicoRV32 firmware. Usage: python conv1_tile_np.py model.pt conv_tile.h
"""
import io, pickle, sys, zipfile
from collections import OrderedDict
import numpy as np

DTYPES = {"FloatStorage": np.float32, "DoubleStorage": np.float64, "LongStorage": np.int64}


def load_state_dict(path):
    """Read a torch.save()'d state_dict. Only tensor-rebuild opcodes are allowed, so no code runs."""
    zf = zipfile.ZipFile(path)
    root = next(n for n in zf.namelist() if n.endswith("/data.pkl"))[:-len("data.pkl")]

    class Storage:
        def __init__(self, name): self.dtype = DTYPES[name]

    def rebuild(storage, offset, size, stride, *unused):
        dtype, key = storage
        flat = np.frombuffer(zf.read(f"{root}data/{key}"), dtype=dtype)
        count = int(np.prod(size)) if size else 1
        return flat[offset:offset + count].reshape(size).copy()

    class Safe(pickle.Unpickler):
        def find_class(self, module, name):
            if (module, name) == ("collections", "OrderedDict"): return OrderedDict
            if (module, name) == ("torch._utils", "_rebuild_tensor_v2"): return rebuild
            if module == "torch" and name in DTYPES: return Storage(name)
            raise pickle.UnpicklingError(f"refusing {module}.{name}")

        def persistent_load(self, pid):
            _, storage, key, _location, _numel = pid
            return storage.dtype, key

    return Safe(io.BytesIO(zf.read(root + "data.pkl"))).load()


def main():
    ckpt = sys.argv[1] if len(sys.argv) > 1 else "model.pt"
    header = sys.argv[2] if len(sys.argv) > 2 else None
    state = load_state_dict(ckpt)
    w, bias = state["conv1.weight"], state["conv1.bias"]
    assert w.shape == (32, 3, 5, 5) and bias.shape == (32,), (w.shape, bias.shape)

    # Same repeatable RGB test image as conv1_tile.py, in (channel, row, column) order, scaled 0..1.
    c, r, col = np.meshgrid(np.arange(3), np.arange(32), np.arange(32), indexing="ij")
    image = (((64 * c + 3 * r + 5 * col) % 256).astype(np.float32)) / np.float32(255)

    # One row of A per image patch, one column of B per filter, both flattened channel,row,column.
    a = np.stack([image[:, 0:5, j:j + 5].reshape(-1) for j in (0, 1)])       # 2 x 75
    b = w[:2].reshape(2, -1).T                                                # 75 x 2
    reference = a.astype(np.float64) @ b.astype(np.float64) + bias[:2]        # float conv1 output

    weight_scale = np.abs(w).max() / np.float32(127)
    a_int = np.clip(np.round(np.float32(127) * a), 0, 127).astype(np.int32)
    b_int = np.clip(np.round(b / weight_scale), -127, 127).astype(np.int32)
    expected = a_int @ b_int                                                  # 2 x 2 exact integers
    dequant = expected * float(weight_scale) / 127 + bias[:2]

    print("Expected signed 32-bit sums:", expected.tolist())
    print("Float conv1 output         :", np.round(reference, 4).tolist())
    print("Dequantized integer sums   :", np.round(dequant, 4).tolist())
    print("Max abs quantization error :", float(np.abs(dequant - reference).max()))

    if header:
        def arr(name, values, ctype="signed char"):
            return f"static const {ctype} {name}[{len(values)}] = {{{', '.join(str(int(v)) for v in values)}}};\n"
        with open(header, "w") as f:
            f.write("/* Generated by conv1_tile_np.py from Adv_Attack model.pt. Do not edit. */\n")
            f.write("#define CONV_K 75\n")
            f.write(arr("CONV_A0", a_int[0])); f.write(arr("CONV_A1", a_int[1]))
            f.write(arr("CONV_B0", b_int[:, 0])); f.write(arr("CONV_B1", b_int[:, 1]))
            f.write(arr("CONV_EXPECTED", expected.reshape(-1), "int"))
        print("wrote", header)


if __name__ == "__main__":
    main()
